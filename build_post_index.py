"""Build a brand's existing-post index from its sitemap.

Reads every post in the sitemap and saves a short summary of each one
(title, description, section headings, opening lines) to
brands/<brand>/posts.md. The interviewer uses this file to spot when an
SME's idea overlaps a post that already exists.

Usage:
    python build_post_index.py content-workshop https://contentworkshop.com/post-sitemap.xml
"""

import html
import re
import sys
import time
import urllib.request
from pathlib import Path

USER_AGENT = "sme-interview-prototype/0.1"
BRANDS_DIR = Path(__file__).parent / "brands"


def fetch(url: str) -> str:
    request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(request, timeout=30) as response:
        return response.read().decode("utf-8", errors="ignore")


def post_urls(sitemap_xml: str) -> list[str]:
    urls = re.findall(r"<loc>([^<]+)</loc>", sitemap_xml)
    return [u for u in urls if "/wp-content/" not in u]


def _clean(fragment: str) -> str:
    text = re.sub(r"<[^>]+>", " ", fragment)
    return re.sub(r"\s+", " ", html.unescape(text)).strip()


def summarize_post(url: str, page: str) -> dict:
    title = re.search(r"<title>(.*?)</title>", page, re.S)
    description = re.search(r'<meta name="description" content="(.*?)"', page)
    date = re.search(r'"datePublished":"([0-9-]{10})', page)
    headings = [_clean(h) for h in re.findall(r"<h2[^>]*>(.*?)</h2>", page, re.S)]
    headings = [h for h in headings if h and h.lower() != "posts navigation"]
    paragraphs = [_clean(p) for p in re.findall(r"<p[^>]*>(.*?)</p>", page, re.S)]
    opening = " ".join(p for p in paragraphs if len(p) > 60)[:400]
    clean_title = _clean(title.group(1)) if title else url
    clean_title = re.sub(r"\s*\|\s*[^|]+$", "", clean_title)
    return {
        "url": url,
        "title": clean_title,
        "date": date.group(1) if date else "",
        "description": html.unescape(description.group(1)) if description else "",
        "headings": headings,
        "opening": opening,
    }


def render(posts: list[dict]) -> str:
    lines = [
        "# Existing Posts",
        "",
        f"{len(posts)} posts. Generated by build_post_index.py. Do not edit by hand.",
        "",
    ]
    for post in posts:
        lines.append(f"## {post['title']}")
        meta = f"URL: {post['url']}"
        if post["date"]:
            meta += f" · Published: {post['date']}"
        lines.append(meta)
        if post["description"]:
            lines.append(f"Summary: {post['description']}")
        if post["headings"]:
            lines.append("Sections: " + " | ".join(post["headings"]))
        if post["opening"]:
            lines.append(f"Opening: {post['opening']}")
        lines.append("")
    return "\n".join(lines)


def main() -> None:
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    brand, sitemap_url = sys.argv[1], sys.argv[2]
    brand_dir = BRANDS_DIR / brand
    if not brand_dir.is_dir():
        sys.exit(f"No brand folder at {brand_dir}")

    urls = post_urls(fetch(sitemap_url))
    print(f"Found {len(urls)} posts. Reading each one...")
    posts = []
    for i, url in enumerate(urls, 1):
        try:
            posts.append(summarize_post(url, fetch(url)))
        except Exception as error:  # keep going if one page fails
            print(f"  skipped {url}: {error}")
        if i % 25 == 0:
            print(f"  {i}/{len(urls)}")
        time.sleep(0.2)  # be polite to the site

    posts.sort(key=lambda p: p["date"], reverse=True)
    out = brand_dir / "posts.md"
    out.write_text(render(posts), encoding="utf-8")
    print(f"Saved {len(posts)} post summaries to {out}")


if __name__ == "__main__":
    main()
